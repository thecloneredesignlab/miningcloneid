# Pure metadata fixture for a reserve parent whose frozen root is 'dispatch'.
args<-commandArgs(trailingOnly=TRUE);stopifnot(length(args)==1L)
s<-normalizePath(args[1]);entry<-file.path(s,'releases/repair02')
source(file.path(entry,'adapter.R'));source(file.path(entry,'helpers.R'))
temp<-tempfile('repair_root_fixture_');dir.create(temp);on.exit(unlink(temp,recursive=TRUE))
for(folder in c('manifests','fits/parent'))dir.create(file.path(temp,folder),recursive=TRUE)
writeLines('opaque source identity',file.path(temp,'manifests/input_manifest.tsv'))
p<-c(x=.2,y=.6);record<-list(parameters=p,components=list(L=2),source_manifest_sha256=hash_file(file.path(temp,'manifests/input_manifest.tsv')))
atomic_rds(list(policy='production',record=record,checked=list(L=2)),file.path(temp,'fits/parent/accepted_candidate.rds'))
atomic_rds(list(root_id='uniform_root_A'),file.path(temp,'fits/parent/dispatch_spec.rds'))
atomic_rds(list(parent=list(mode='local',root_id='dispatch')),file.path(temp,'manifests/task_specs.rds'))
finalize_payload(file.path(temp,'fits/parent'))
ctx<-list(study=temp,endpoint=p,lower=c(x=0,y=0),upper=c(x=1,y=1))
spec<-list(selector='task',source_task='parent',policy='production',root_id='uniform_root_A',role='reserve_fresh')
z<-resolve_start(ctx,spec);stopifnot(identical(z$parameters,p),z$root_id=='uniform_root_A')
spec$root_id<-'archive_root_B';bad<-tryCatch({resolve_start(ctx,spec);FALSE},error=function(e)TRUE);stopifnot(bad)
out<-file.path(s,'tests/root_metadata_bridge');dir.create(out,recursive=TRUE,showWarnings=FALSE)
write_kv(list(pass=TRUE,correct_parent_resolved=TRUE,cross_root_rejected=TRUE,model_evaluations=0L,
 kind='pure_metadata',parent_release='repair01',new_release='repair02'),file.path(out,'result.tsv'))
finalize_payload(out);unlink(temp,recursive=TRUE);cat('Reserve root metadata: actual dispatch root accepted; wrong root rejected; zero model calls.\n')
