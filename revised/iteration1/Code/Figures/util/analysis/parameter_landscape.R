# Start each label outside the densest part of its cluster. The nudge direction
# is derived from the cluster median relative to the full endpoint cloud, so it
# remains deterministic when the selected number of clusters changes.
tsne_global_center <- c(
  tSNE1 = median(clusters$tSNE1),
  tSNE2 = median(clusters$tSNE2)
)
tsne_visible_labels <- copy(tsne_centers)
tsne_visible_labels[, `:=`(
  direction_x = tSNE1 - tsne_global_center[["tSNE1"]],
  direction_y = tSNE2 - tsne_global_center[["tSNE2"]]
)]
tsne_visible_labels[, direction_norm := sqrt(direction_x^2 + direction_y^2)]
zero_direction <- !is.finite(tsne_visible_labels$direction_norm) |
  tsne_visible_labels$direction_norm < 1e-12
if (any(zero_direction)) {
  fallback_angles <- seq(
    0,
    2 * pi,
    length.out = sum(zero_direction) + 1L
  )[-(sum(zero_direction) + 1L)]
  tsne_visible_labels[zero_direction, `:=`(
    direction_x = cos(fallback_angles),
    direction_y = sin(fallback_angles),
    direction_norm = 1
  )]
}
tsne_visible_labels[, `:=`(
  nudge_x = direction_x / direction_norm * tsne_span * 0.10,
  nudge_y = direction_y / direction_norm * tsne_span * 0.10
)]
tsne_visible_labels[, label := sprintf(
