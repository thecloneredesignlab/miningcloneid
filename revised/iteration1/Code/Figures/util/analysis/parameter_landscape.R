#!/usr/bin/env Rscript

# Build the aligned fixed-O2 and fitted-landscape parameter summary.
# The historical script and intermediate-output basenames retain "historical panel".
#
# The shared parameter rows link:
#   1. signed single-parameter AUC across 201 fixed-O2 concentrations;
#   2. each parameter's peak discriminative AUC and the O2 at that peak;
#   3. cluster-wise prior-referenced parameter positions for exploratory groups
#      of the 500 separate in vivo fitted endpoints.
#
# A complete 18-parameter faceted violin plot is exported as a supplementary
# figure. The main combined panel uses median/IQR/5th-95th intervals because
# 54 full violins would make the manuscript panel unreadable.

suppressPackageStartupMessages({
  library(data.table)
  library(ggrepel)
  library(ggplot2)
  library(patchwork)
  library(scales)
})

script_path <- local({
  file_arg <- grep("^--file=", commandArgs(trailingOnly = FALSE), value = TRUE)
  if (length(file_arg)) {
    normalizePath(sub("^--file=", "", file_arg[[1L]]), mustWork = FALSE)
  } else {
    normalizePath("parameter_landscape.R", mustWork = FALSE)
  }
})
script_dir <- dirname(script_path)
data_dir <- normalizePath(
  Sys.getenv("ANALYSIS_DATA_DIR", unset = file.path(script_dir, "data")),
  mustWork = TRUE
)
figure_dir <- normalizePath(
  Sys.getenv(
    "PLOT_OUTPUT_DIR",
    unset = file.path(script_dir, "figures")
  ),
  mustWork = FALSE
)
dir.create(data_dir, recursive = TRUE, showWarnings = FALSE)
dir.create(figure_dir, recursive = TRUE, showWarnings = FALSE)

auc_path <- file.path(data_dir, "parameter_auc_by_o2.tsv")
parameter_meta_path <- file.path(data_dir, "parameter_function_groups.tsv")
parameter_palette_path <- file.path(data_dir, "parameter_function_group_palette.tsv")
best_parameter_path <- file.path(data_dir, "invivo_best_parameters_500seeds.tsv")
cluster_path <- file.path(
  data_dir,
  "invivo_best_tsne_cluster_coordinates.tsv"
)
cluster_summary_path <- file.path(
  data_dir,
  "invivo_tsne_cluster_summary.tsv"
)
tsne_run_metadata_path <- file.path(data_dir, "invivo_tsne_run_metadata.tsv")
bound_path <- file.path(data_dir, "invivo_parameter_table_seed25.csv")

required_paths <- c(
  auc_path, parameter_meta_path, parameter_palette_path, best_parameter_path, cluster_path,
  cluster_summary_path, tsne_run_metadata_path, bound_path
)
missing_paths <- required_paths[!file.exists(required_paths)]
if (length(missing_paths)) {
  stop("Missing aligned parameter landscape input(s): ", paste(missing_paths, collapse = ", "))
}

auc <- fread(auc_path)
parameter_meta <- fread(parameter_meta_path)
parameter_palette_meta <- fread(parameter_palette_path)
best_parameters <- fread(best_parameter_path)
clusters_raw <- fread(cluster_path)[dataset == "invivo"]
cluster_summary <- fread(cluster_summary_path)[dataset == "invivo"]
tsne_run_metadata <- fread(tsne_run_metadata_path)
bounds <- fread(bound_path)
tsne_metric <- function(key_name) {
  value <- tsne_run_metadata[tsne_run_metadata$key == key_name, value]
  if (length(value) != 1L) {
    stop("Missing or duplicated in vivo t-SNE run metadata key: ", key_name)
  }
  as.character(value[[1L]])
}
if (tsne_metric("fit_scope") != "separate_in_vivo_only" ||
    as.integer(tsne_metric("retained_initial_rows")) != 127500L ||
    as.integer(tsne_metric("best_endpoint_rows")) != 500L ||
    as.integer(tsne_metric("total_tsne_rows")) != 128000L ||
    as.integer(tsne_metric("tsne_parameters")) != 18L ||
    tsne_metric("excluded_variables") != "rho_2N,sigma_burden") {
  stop("The t-SNE run metadata does not match the approved analysis contract.")
}

required_auc_columns <- c(
  "O2_pct", "parameter", "parameter_group", "raw_auc_ge_2_positive",
  "discriminative_auc", "signed_auc_for_color", "direction"
)
if (!all(required_auc_columns %in% names(auc))) {
  stop("AUC table is missing: ", paste(setdiff(required_auc_columns, names(auc)), collapse = ", "))
}
if (nrow(auc) != 18L * 201L ||
    uniqueN(auc$parameter) != 18L ||
    uniqueN(auc$O2_pct) != 201L) {
  stop("Aligned parameter landscape requires 18 parameters x 201 O2 values.")
}
if (nrow(parameter_meta) != 18L || !identical(parameter_meta$parameter_order, seq_len(18L))) {
  stop("Parameter metadata must contain the ordered 18-parameter parameter landscape set.")
}
if (nrow(parameter_palette_meta) != 5L ||
    !identical(parameter_palette_meta$group_order, seq_len(5L)) ||
    !setequal(parameter_meta$parameter_group, parameter_palette_meta$parameter_group)) {
  stop("Parameter-function palette must define the five ordered response groups.")
}

# The AUC table retains the historical parameter-group labels generated by the
# fixed-O2 workflow. Replace those labels with the current shared response
# taxonomy without changing any AUC values.
auc[, c("parameter_group") := NULL]
auc <- merge(
  auc,
  parameter_meta[, .(parameter, parameter_group, parameter_order)],
  by = "parameter",
  all.x = TRUE,
  sort = FALSE
)
setorder(auc, parameter_order, O2_pct)

clusters <- clusters_raw[, .(
  seed_number = as.integer(seed),
  tSNE1 = as.numeric(tSNE1),
  tSNE2 = as.numeric(tSNE2),
  cluster_id,
  cluster_num = as.integer(cluster_num),
  cluster_k = as.integer(cluster_k),
  cluster_silhouette_avg = as.numeric(cluster_silhouette_avg)
)]
if (nrow(best_parameters) != 500L || nrow(clusters) != 500L ||
    anyDuplicated(best_parameters$seed_number) || anyDuplicated(clusters$seed_number)) {
  stop("Aligned parameter landscape requires 500 unique fitted endpoints and cluster assignments.")
}

merged <- merge(best_parameters, clusters, by = "seed_number", all = FALSE)
setorder(merged, seed_number)
if (nrow(merged) != 500L || !identical(merged$seed_number, seq_len(500L))) {
  stop("Parameter/cluster join did not recover seed 1 through seed 500 exactly once.")
}

observed_sizes <- table(merged$cluster_id)
cluster_summary_sizes <- setNames(
  as.integer(cluster_summary$n_seeds),
  as.character(cluster_summary$cluster_id)
)
cluster_levels <- sprintf(
  "vi_C%02d",
  seq_len(length(cluster_summary_sizes))
)
cluster_summary_sizes <- cluster_summary_sizes[cluster_levels]
if (anyNA(cluster_summary_sizes) ||
    !identical(
      as.integer(observed_sizes[cluster_levels]),
      unname(cluster_summary_sizes)
    ) ||
    sum(cluster_summary_sizes) != 500L) {
  stop("Cluster assignments do not match the generated in vivo t-SNE summary.")
}
selected_k <- unique(merged$cluster_k)
selected_silhouette <- unique(merged$cluster_silhouette_avg)
if (length(selected_k) != 1L ||
    selected_k != length(cluster_levels) ||
    length(selected_silhouette) != 1L ||
    !is.finite(selected_silhouette)) {
  stop("The generated in vivo t-SNE cluster metadata is inconsistent.")
}

all_parameters <- parameter_meta$parameter
cluster_input_parameters <- all_parameters
projected_only_parameters <- setdiff(all_parameters, cluster_input_parameters)
if (length(projected_only_parameters)) {
  stop(
    "All 18 displayed parameters must be inputs to the in vivo-only t-SNE."
  )
}

bound_meta <- bounds[
  estimate == TRUE & param_prototype %in% all_parameters,
  .(
    parameter = param_prototype,
    optimizer_parameter = param_name,
    lower_bound = as.numeric(prototype_lower_bound),
    upper_bound = as.numeric(prototype_upper_bound),
    transformation = ifelse(grepl("^log10_", param_name), "log10", "identity")
  )
]
if (nrow(bound_meta) != 18L || !setequal(bound_meta$parameter, all_parameters)) {
  stop("Could not recover configured bounds for all 18 parameters.")
}

prior_sd <- sqrt(1 / 12)
parameter_long <- rbindlist(lapply(all_parameters, function(parameter_name) {
  meta <- bound_meta[parameter == parameter_name]
  values <- as.numeric(merged[[parameter_name]])
  lower_natural <- meta$lower_bound[[1L]]
  upper_natural <- meta$upper_bound[[1L]]
  if (identical(meta$transformation[[1L]], "log10")) {
    if (any(!is.finite(values) | values <= 0) ||
        lower_natural <= 0 || upper_natural <= 0) {
      stop("Non-positive log10 value for ", parameter_name)
    }
    transformed <- log10(values)
    lower_transformed <- log10(lower_natural)
    upper_transformed <- log10(upper_natural)
  } else {
    transformed <- values
    lower_transformed <- lower_natural
    upper_transformed <- upper_natural
  }
  prior_unit <- (transformed - lower_transformed) /
    (upper_transformed - lower_transformed)
  data.table(
    seed_number = merged$seed_number,
    cluster_id = merged$cluster_id,
    tSNE1 = merged$tSNE1,
    tSNE2 = merged$tSNE2,
    parameter = parameter_name,
    natural_value = values,
    transformed_value = transformed,
    prior_unit = prior_unit,
    prior_referenced_z = (prior_unit - 0.5) / prior_sd,
    transformation = meta$transformation[[1L]],
    lower_bound = lower_natural,
    upper_bound = upper_natural,
    cluster_role = ifelse(
      parameter_name %in% cluster_input_parameters,
      "Used in 18-parameter in vivo-only t-SNE construction",
      "Projected onto existing clusters only"
    )
  )
}))

parameter_long <- merge(
  parameter_long,
  parameter_meta[, .(
    parameter, parameter_group, parameter_description, parameter_order
  )],
  by = "parameter",
  all.x = TRUE,
  sort = FALSE
)
setorder(parameter_long, parameter_order, seed_number)
if (nrow(parameter_long) != 18L * 500L ||
    any(!is.finite(parameter_long$prior_referenced_z))) {
  stop("The 18-parameter prior-referenced table is incomplete or non-finite.")
}

cluster_intervals <- parameter_long[, .(
  n = .N,
  median_prior_z = median(prior_referenced_z),
  q05_prior_z = quantile(prior_referenced_z, 0.05),
  q25_prior_z = quantile(prior_referenced_z, 0.25),
  q75_prior_z = quantile(prior_referenced_z, 0.75),
  q95_prior_z = quantile(prior_referenced_z, 0.95),
  mean_prior_z = mean(prior_referenced_z),
  natural_median = median(natural_value),
  natural_q25 = quantile(natural_value, 0.25),
  natural_q75 = quantile(natural_value, 0.75)
), by = .(
  parameter, parameter_group, parameter_order, cluster_role, cluster_id
)]

cluster_difference <- parameter_long[, {
  grand_mean <- mean(prior_unit)
  total_ss <- sum((prior_unit - grand_mean)^2)
  between_ss <- sum(vapply(
    split(prior_unit, cluster_id),
    function(x) length(x) * (mean(x) - grand_mean)^2,
    numeric(1)
  ))
  .(
    eta_squared_cluster = if (total_ss > 0) between_ss / total_ss else NA_real_,
    max_pairwise_cluster_mean_difference = {
      means <- tapply(prior_referenced_z, cluster_id, mean)
      max(means) - min(means)
    }
  )
}, by = .(parameter, parameter_group, parameter_order, cluster_role)]
setorder(cluster_difference, -eta_squared_cluster, parameter_order)
cluster_difference[, rank_eta_squared := seq_len(.N)]

peak_auc <- auc[, {
  maximum <- max(discriminative_auc, na.rm = TRUE)
  candidates <- .SD[abs(discriminative_auc - maximum) < 1e-12]
  candidates <- candidates[order(O2_pct)]
  candidates[1L]
}, by = .(parameter, parameter_group, parameter_order)]
peak_auc[, peak_direction_class := fifelse(
  raw_auc_ge_2_positive > 0.5,
  "Higher values associated with dominant_mean_ploidy >= 2",
  "Higher values associated with dominant_mean_ploidy < 2"
)]

